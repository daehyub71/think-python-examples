# 생각하는 파이썬 Part 2 · 작은 정수
# (강의 슬라이드: 256 은 같고 257 은 다르다?)


a = 256
b = 256
print(a is b)               # True — -5 ~ 256 은 미리 하나씩 만들어 두고 함께 쓴다

a = 257
b = 257
print(a is b)               # 이 파일로 실행하면 True, 대화형 모드에서 한 줄씩 치면 False
                            # (파일은 통째로 번역하면서 같은 숫자를 하나로 합친다)

# 실행 방식에 따라 달라지는 것은 약속된 동작이 아닙니다.
# 값이 같은지는 언제나 == 로 묻습니다.
print(a == b)               # True — 어디서 실행해도
