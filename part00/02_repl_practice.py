# 대화형 모드(>>>)에서는 식만 쳐도 답이 나오지만,
# 파일로 실행할 때는 print()로 감싸야 화면에 보입니다.
print(1 + 1)                    # 2
print("안녕, 파이썬!")
print((88 + 92 + 79) / 3)       # 86.33333333333333
print(12000 * 1.1)              # 13200.000000000002  ← 이유는 Part 1에서

# 직접 해보기
print(10 * 9)                   # 90
print("파이썬" * 3)              # 파이썬파이썬파이썬
print(2 ** 10)                  # 1024
print(28000 / 4)                # 7000.0
