# 생각하는 파이썬 Part 4 · 리스트 바꾸기
# (강의 슬라이드: 리스트는 살아 움직이는 그릇)

sales = [120, 340, 90, 510, 280]
sales[1] = 999              # 자리의 값 바꾸기
print(sales)                # [120, 999, 90, 510, 280]

box = [5, 6]
box.append([7, 8])          # 상자째로 넣기
print(box)                  # [5, 6, [7, 8]]

box = [5, 6]
box.extend([7, 8])          # 상자를 열어 내용물만 붓기
print(box)                  # [5, 6, 7, 8]
