# 생각하는 파이썬 Part 4 · 딕셔너리 기본
# (강의 슬라이드: 딕셔너리 · KeyError)

stock = {"A-101": 50, "A-102": 30}  # 키: 값
print(stock["A-101"])       # 50 — 번호 대신 키로 꺼낸다

stock["A-101"] = 45         # 있는 키 → 수정
stock["A-103"] = 100        # 없는 키 → 추가 (키를 잘못 치면 엉뚱한 항목이 생긴다!)
del stock["A-102"]          # 삭제
print(stock)                # {'A-101': 45, 'A-103': 100}

