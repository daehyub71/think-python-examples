# 생각하는 파이썬 Part 4 · 별칭과 복사
# (강의 슬라이드: b = a — 별칭)

a = [7, 8, 9]
b = a                       # 복사가 아니라 이름표를 한 장 더 붙인 것
b.append(10)
print(a)                    # [7, 8, 9, 10] ← b 에 붙였는데 a 가 바뀌었다

a = [7, 8, 9]
b = a[:]                    # 전체를 잘라 새 리스트로 (a.copy() 도 같다)
b.append(10)
print(a)                    # [7, 8, 9]
print(b)                    # [7, 8, 9, 10]
