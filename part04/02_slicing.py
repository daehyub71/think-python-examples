# 생각하는 파이썬 Part 4 · 슬라이싱
# (강의 슬라이드: 슬라이싱)

sales = [120, 340, 90, 510, 280]
#       0    1    2   3    4    5     ← 칸막이 번호
#       | 120| 340| 90| 510| 280|

print(sales[1:4])           # [340, 90, 510] — 1번 칸막이부터 4번 칸막이까지
print(sales[:3])            # [120, 340, 90] — 처음부터
print(sales[3:])            # [510, 280]     — 끝까지
