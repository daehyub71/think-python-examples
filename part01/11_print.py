# 생각하는 파이썬 Part 1 · print
# (강의 슬라이드: print() — 옵션 두 개)


print("재고:", 1200, "개")                   # 재고: 1200 개  (쉼표로 여러 값, 한 칸씩 띄운다)
print("2026", "10", "06", sep="-")          # 2026-10-06     (sep — 값 사이에 넣을 것)
print("저장 중", end=""); print("... 완료")   # 저장 중... 완료 (end — 끝에 붙일 것, 기본은 줄바꿈)

# 세미콜론(;)은 두 명령을 한 줄에 적은 것입니다.
