# 생각하는 파이썬 Part 1 · f-string
# (강의 슬라이드: f-string · 콜론 뒤의 서식)


product = "무선 마우스"
stock = 1200
print(f"{product}의 재고는 {stock}개입니다")
print(f"재고 자산은 {stock * 3500}원")        # 중괄호 안에 계산식도 된다

# 콜론 뒤의 서식
print(f"{4200000:,}")       # 4,200,000   천 단위 쉼표
print(f"{86.3333:.2f}")     # 86.33       소수 둘째 자리
print(f"{'합계':>10}")       # 폭 10, 오른쪽 정렬
print(f"{0.4567:.1%}")      # 45.7%       백분율

# 서식은 보여 주는 모양만 바꿉니다. 값 자체는 그대로입니다.
