# 생각하는 파이썬 Part 1 · == 와 is
# (강의 슬라이드: == 는 내용, is 는 "바로 그 물건")


a = [1, 2, 3]               # 대괄호로 값 여러 개를 묶은 것 = 리스트
b = [1, 2, 3]               # 내용이 같은 새 리스트
c = a                       # 이름표 하나 더

print(a == b)               # True  — 내용이 같다
print(a is b)               # False — 따로 만든 두 리스트
print(a is c)               # True  — 같은 리스트에 붙은 이름표 두 장

# 값을 비교할 때는 거의 항상 == 를 씁니다. is 는 x is None 에서만.
